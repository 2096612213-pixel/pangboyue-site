import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const parts = [
  'document-head.html',
  'header.html',
  'hero.html',
  'agent-chat.html',
  'archive-cards.html',
  'footer.html',
];
const htmlTemplate = (await Promise.all(parts.map(name =>
  readFile(join(root, 'src', 'home', name), 'utf8')))).join('');
const scripts = [
  'overscroll.js',
  'dropdowns.js',
  'lazy-images.js',
  'route-prefetch.js',
  'clock.js',
  'home-scenes.js',
  'deferred-features.js',
];
const styleSources = ['src/home/styles/base.css', 'src/home/styles/clouds.css', 'src/home/styles/scenes.css', 'src/home/styles/chat.css'];
const stylesheet = '/* Generated by scripts/build-home.mjs; edit the original CSS files. */\n' +
  (await Promise.all(styleSources.map(path => readFile(join(root, path), 'utf8')))).join('\n');
const javascript = (await Promise.all(scripts.map(name =>
  readFile(join(root, 'src', 'home', 'scripts', name), 'utf8')))).join('');
const fingerprint = content => createHash('sha256').update(content).digest('hex').slice(0, 12);
const versions = {
  __HOME_STYLE_HASH__: fingerprint(stylesheet),
  __ASTRONOMY_JS_HASH__: fingerprint(await readFile(join(root, 'assets/home/scenes/astronomy.browser.min.js'))),
  __STORM_JS_HASH__: fingerprint(await readFile(join(root, 'assets/home/scenes/storm-sound.js'))),
  __BLOSSOM_HTML_HASH__: fingerprint(await readFile(join(root, 'visibleproductsshow/silver-blossom/index.html'))),
  __MOUNTAIN_JS_HASH__: fingerprint(await readFile(join(root, 'visibleproductsshow/mountain-home/bundle.js'))),
  __LANDSCAPE_AVIF_2X_HASH__: fingerprint(await readFile(join(root, 'images/home/xiangjiang-4318.avif'))),
  __LANDSCAPE_WEBP_2X_HASH__: fingerprint(await readFile(join(root, 'images/home/xiangjiang-4318.webp'))),
  __LANDSCAPE_AVIF_HASH__: fingerprint(await readFile(join(root, 'images/home/xiangjiang-2159.avif'))),
  __LANDSCAPE_WEBP_HASH__: fingerprint(await readFile(join(root, 'images/home/xiangjiang-2159.webp'))),
  __AGENT_BACKDROP_HASH__: fingerprint(await readFile(join(root, 'assets', 'home', 'agent-chat', 'backdrop.js'))),
  __AGENT_JS_HASH__: fingerprint(await readFile(join(root, 'assets', 'home', 'agent-chat', 'chat.js'))),
  __AGENT_ICON_HASH__: fingerprint(await readFile(join(root, 'assets', 'home', 'agent-chat', 'psi.svg'))),
  __FLUID_JS_HASH__: fingerprint(await readFile(join(root, 'assets/home/scenes/fluid-tank.js'))),
  __HOME_JS_HASH__: fingerprint(javascript),
};
const html = Object.entries(versions).reduce(
  (page, [token, hash]) => page.replaceAll(token, hash),
  htmlTemplate,
);
const targets = [
  [join(root, 'index.html'), html],
  [join(root, 'assets/home/main.js'), javascript],
  [join(root, 'assets/home/main.css'), stylesheet],
];

if (process.argv.includes('--check')) {
  const stale = [];
  for (const [path, expected] of targets) {
    if (await readFile(path, 'utf8') !== expected) stale.push(path);
  }
  if (stale.length) {
    console.error('构建文件与 src/home/ 不一致，请运行 node scripts/build-home.mjs');
    process.exitCode = 1;
  } else {
    console.log('首页 HTML、交互脚本和合并样式已同步。');
  }
} else {
  await Promise.all(targets.map(([path, content]) => writeFile(path, content)));
  console.log('已生成 index.html、assets/home/main.js 和 assets/home/main.css');
}
