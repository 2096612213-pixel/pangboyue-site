import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// Keep editable modules/CSS, but publish a single startup module and inline the
// small layout styles. No random manifest request or eager player/media load.
const root = new URL('../favorsongs/', import.meta.url);
const check = process.argv.includes('--check');
const read = name => readFile(new URL(name, root), 'utf8');
const hash = text => createHash('sha256').update(text).digest('hex').slice(0,12);
const pending = new Map();
const value = async name => pending.get(name) ?? await read(name);
for (const [host, asset] of [
  ['vinyl-player.html','vinyl-bridge.js'],
  ['vinyl-desktop.js','vinyl-player.html'],
  ['playlist.js','vinyl-desktop.js'],
]) {
  const text = await read(host);
  const pattern = new RegExp(asset.replaceAll('.', '\\.') + '\\?v=[a-f0-9]+', 'g');
  if (!pattern.test(text)) throw Error(`Missing ${asset} reference in ${host}`);
  pending.set(host, text.replace(pattern, `${asset}?v=${hash(await value(asset))}`));
}
const source = await value('playlist.js');
const manifest = await read('songs.js');
const importLine = "import { songs as addedSongs } from './songs.js';";
if (!source.includes(importLine) || !manifest.startsWith('export const songs =')) throw Error('Unexpected playlist/manifest format');
const bundle = '// Generated by scripts/build-favorsongs.mjs; edit playlist.js and songs.js.\n' +
  source.replace(importLine, manifest.replace('export const songs =', 'const addedSongs ='));
pending.set('playlist.bundle.js', bundle);
const styles = (await Promise.all(['alphabet.css','vinyl-desktop.css'].map(read))).join('\n');
let html = await read('index.html');
const marker = /<!-- songs:styles:start -->[\s\S]*?<!-- songs:styles:end -->/;
if (!marker.test(html)) throw Error('Missing generated stylesheet markers');
html = html.replace(marker, `<!-- songs:styles:start -->\n  <style>\n${styles}  </style>\n  <!-- songs:styles:end -->`);
html = html.replace(/playlist\.bundle\.js\?v=[a-f0-9]+/g, `playlist.bundle.js?v=${hash(bundle)}`);
pending.set('index.html', html);
for (const [name, content] of pending) {
  if (check) {
    if (await read(name) !== content) throw Error(`${name} is stale; run npm run build:songs`);
  } else await writeFile(new URL(name, root), content);
}
console.log(check ? '歌曲页入口、样式与播放器指纹已同步。' : '已生成歌曲页轻量入口并更新内容指纹。');
